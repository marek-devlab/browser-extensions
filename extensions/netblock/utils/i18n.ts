const messages: Catalog<MsgKey> = { en, ru, et };

const translate = createTranslator<MsgKey>(messages);

/** Hook: a locale-bound `t()` for React surfaces (popup + tool page). */
export function useT(): TFn {
  const locale = useLocale();
  return useCallback(
    (key: MsgKey, vars?: Record<string, string | number>) => translate(locale, key, vars),
    [locale],
  );
}

/** Imperative translator for non-React callers (background toasts, badge). */
export function tAt(locale: Locale, key: MsgKey, vars?: Record<string, string | number>): string {
  return translate(locale, key, vars);
}

/** Message key for a design-§6 honesty note. Typed so a new HonestyKey without
 *  a string fails the build here rather than rendering a raw key. */
/** Reason strings this extension emits itself (engines/debugger.ts) → i18n;
 *  anything else is the browser's own wording and is shown verbatim. */
const OWN_REASONS: Record<string, MsgKey> = {
  [OWN_REASON.handlerErrors]: 'nlReason.handlerErrors',
  [OWN_REASON.watchdog]: 'logError.watchdog',
};
export function translateReason(t: TFn, reason: string): string {
  const key = OWN_REASONS[reason];
  return key ? t(key) : reason;
}

export function honestyKey(k: HonestyKey): MsgKey {
  return `honesty.${k}`;
}

const ENGINE_KEYS: Record<EngineId, { short: MsgKey; long: MsgKey }> = {
  dnr: { short: 'engineDnr', long: 'engineDnrLong' },
  page: { short: 'enginePage', long: 'enginePageLong' },
  debugger: { short: 'engineDebugger', long: 'engineDebuggerLong' },
  webrequest: { short: 'engineWebrequest', long: 'engineWebrequestLong' },
};

/** Badge text for an engine; `↓` marks a degraded run (design §2.8, §9.2). */
export function engineBadge(t: TFn, engine: EngineId, degraded: boolean): string {
  return t(ENGINE_KEYS[engine].short) + (degraded ? '↓' : '');
}

export function engineExplanation(t: TFn, engine: EngineId): string {
  return t(ENGINE_KEYS[engine].long);
}
