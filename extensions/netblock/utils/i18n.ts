// the default (see @blur/ui's DEFAULT_LOCALE); `ru` and `et` are complete
// mirrors — the `Record<MsgKey, string>` typing fails the build if a key is
// missing in any locale. Switching the locale re-renders every surface.
//
// 🔴 Deliberately NOT translated (facts about the browser / house rules):
//   - Engine badges (`dnr`/`page`/`dbg`/`wr`/`wr↓`), marks (✱ ≈ ○), HTTP
//     methods and status codes, resource-type tokens (xhr, script, …), CDP
//     error reasons (TimedOut, ConnectionReset, …), API names
//     (declarativeNetRequest, webRequest, storage.session), URLs, numbers,
//     units (ms, s, KB).
//   - Storage keys, CSS classes, console text, comments.
//
// The `honesty.*` block is design §6 verbatim — the one place the UI admits
// what each engine cannot do. Every HonestyKey MUST have an entry (typed below).
//
// Store-review note (design §11): no "adblock", "privacy" or "tracker" wording
// anywhere in this catalog — this is a resilience-testing tool, not a blocker
// of ads, and the review reads UI copy literally.

